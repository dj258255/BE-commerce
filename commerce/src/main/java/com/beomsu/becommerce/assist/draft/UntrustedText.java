package com.beomsu.becommerce.assist.draft;

/**
 * 프롬프트에 실리는 <b>남이 쓴 문장</b>을 한 줄로 눌러 담는다.
 *
 * <p><b>왜 필요한가</b>: 사실 묶음의 문장이 전부 코드가 만든 것은 아니다. 분쟁 사유는
 * <b>카드사가 보낸 웹훅 페이로드</b>에서 오고, 대사 확정 노트는 운영자가 쓴다. 그 값이
 * 타임라인 요약에 그대로 실려 프롬프트까지 간다.
 *
 * <p>거기에 개행과 지시문을 넣으면 모델이 <b>사실이 아니라 새 지시로</b> 읽을 수 있다.
 * 결제 도메인 실사례로 송금 메모 필드를 통한 인젝션이 보고돼 있다.
 *
 * <p><b>이걸로 인젝션이 막히지는 않는다.</b> 완벽 차단이 불가능하다는 것은 업계의 공통
 * 인정이다. 여기서 하는 일은 <b>가장 싼 표면을 없애는 것</b>뿐이다 — 줄바꿈으로 목록 구조를
 * 깨거나, 긴 문장으로 프롬프트를 밀어내는 것.
 *
 * <p><b>진짜 방어선은 권한이다.</b> 이 모듈은 상태를 바꾸지 않고, 출력은 사람이 원본 목록과
 * 나란히 본다. 뚫려도 할 수 있는 것이 <b>사람에게 거짓말하는 것</b>까지이고 장부는 못 바꾼다
 * (ADR-008). 막는 것이 아니라 뚫린다고 가정하고 권한을 설계한다.
 */
public final class UntrustedText {

    /** 한 줄이 이보다 길면 자른다. 긴 문장으로 앞의 지시를 밀어내는 것을 막는다. */
    static final int MAX_LENGTH = 200;

    private UntrustedText() {
    }

    /**
     * 개행·제어문자를 공백으로 바꾸고, 연속 공백을 줄이고, 길이를 자른다.
     *
     * <p>내용을 검열하지 않는다. <b>구조만 지킨다</b> — 한 줄은 한 줄로 남게 한다.
     * 무엇이 위험한 문장인지 판정하려 들면 그 판정이 또 틀린다.
     */
    public static String flatten(String raw) {
        if (raw == null) {
            return "";
        }
        String s = raw.replaceAll("[\\p{Cntrl}\\p{Zl}\\p{Zp}]", " ")
                .replaceAll("\\s{2,}", " ")
                .strip();
        if (s.length() <= MAX_LENGTH) {
            return s;
        }
        return s.substring(0, MAX_LENGTH) + "…(잘림)";
    }
}
