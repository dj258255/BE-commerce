package com.beomsu.becommerce.assist.draft;

import org.springframework.stereotype.Component;

/**
 * 케이스에 맞는 예시를 골라 싣는다 (ADR-014).
 *
 * <p><b>왜 고정 예시로는 안 되나</b>: 예시 하나가 "고객님께 청구된 금액에는 변동이 없습니다"로
 * 끝나 있었다. 수수료 차감 건에는 맞는 말인데, 모델이 <b>기록조차 없는 건에도 그 꼴을 복사</b>했다.
 * 다른 계열 심판이 잡은 근거 없는 단정의 55%가 여기서 나왔다.
 *
 * <p>정적 프롬프트의 한계로 알려진 것이다 — 예시가 실제 입력과 크게 다르면 일반화가 안 되고
 * 편차가 커진다. 처방은 <b>입력에 맞는 예시를 고르는 것</b>이다.
 *
 * <p><b>프롬프트가 길어지지 않는다.</b> 예시를 세 개 고정으로 싣던 것을
 * <b>맞는 것 하나 + 나쁜 예 하나</b>로 바꾼다. 지시를 더할 때마다 나빠졌던 것(실험 5·6)을
 * 되풀이하지 않으려면, 늘리지 말고 <b>갈아 끼워야</b> 한다.
 *
 * <p><b>핵심은 "모른다"를 가르치는 것이다.</b> 원인을 모르는 건에는
 * <b>모른다고 쓰는 예시</b>를 준다. 확언하는 예시만 보여주면 모델은 확언한다 —
 * 모른다고 말할 줄 아는 것이 맞는 답을 내는 것만큼 중요하다.
 */
@Component
public class DraftExamples {

    /** 원인이 산수로 확정된 건 — <b>결과를 말해도 된다.</b> */
    private static final String DECISIVE = """
            [예시 — 원인이 확인된 경우]
            사실: 결제 승인 10,000원 / 정산 9,730원 / 차액 270원 = 수수료율과 일치
            좋은 초안:
              2026-08-30 결제 10,000원이 정상 승인되었습니다.
              결제사 정산 내역에는 수수료가 차감된 9,730원으로 기록되어 있으며,
              차액 270원은 결제 수수료입니다. 고객님께 청구된 금액에는 변동이 없습니다.
            """;

    /**
     * 원인을 모르는 건 — <b>결과를 말하면 안 된다.</b>
     *
     * <p>"추가로 청구되는 금액은 없습니다"는 <b>사실 주장이 아니라 우리 쪽 약속</b>이라
     * 근거 없이 단정하는 것과 다르다. 이 구분을 예시로 보여준다.
     */
    private static final String UNKNOWN_CAUSE = """
            [예시 — 원인을 아직 모르는 경우] ← 이 경우가 가장 중요합니다
            사실: 결제 승인 10,000원 / 정산 1,112원 / 차액 8,888원 / 수수료로도 취소로도 설명 안 됨
            좋은 초안:
              2026-08-30 결제 10,000원이 승인된 기록은 정상 확인됩니다.
              다만 결제사 정산 내역의 금액이 달라 차액 8,888원의 원인을 확인 중입니다.
              확인이 끝날 때까지 추가로 청구되는 금액은 없으며, 결과가 나오는 대로 안내드리겠습니다.

            주의: 원인을 모를 때 "청구 금액은 그대로입니다"처럼 <결과를 단정하지 마십시오>.
              모르는 것은 모른다고 쓰는 것이 답입니다.
              "추가로 청구되지 않겠다"는 우리가 지킬 약속이라 써도 되지만,
              "이미 청구된 것이 멀쩡하다"는 확인되지 않은 주장입니다.
            """;

    /** 우리 기록에 없는 건 — <b>고객에게 무엇을 부탁할지</b>를 쓴다. */
    private static final String NO_INTERNAL_RECORD = """
            [예시 — 저희 기록에서 찾지 못한 경우]
            사실: 대사 결과 외부 기록에만 있음. 내부에 이 주문 기록 없음. 외부 금액 50,000원
            좋은 초안:
              문의하신 50,000원 결제 건은 결제사 내역에서는 확인되지만
              저희 주문 내역에서 찾지 못해 결제사와 함께 확인하고 있습니다.
              카드사 승인 내역을 보내주시면 확인이 빨라집니다.

            주의: 저희 기록이 없으므로 <청구가 정상이라고 말할 근거가 없습니다>.
              "청구 금액은 그대로 유지됩니다" 같은 문장을 쓰지 마십시오.
            """;

    /** 정산 자료가 늦은 건 — 결제 자체는 무사하다. */
    private static final String FILE_DELAY = """
            [예시 — 결제사 자료가 늦은 경우]
            사실: 승인 10,000원 / 정산 파일에 아직 없음 / 취소 이력 없음
            좋은 초안:
              2026-08-30 결제 10,000원은 정상적으로 승인 완료되었습니다.
              결제사 정산 자료가 늦게 도착해 확인을 이어가고 있으며, 결제 자체에는 문제가 없습니다.
              자료가 도착하는 대로 확인해 안내드리겠습니다.
            """;

    /**
     * 어느 경우에나 보여주는 나쁜 예. <b>피할 것은 말보다 보여주는 쪽이 전달된다.</b>
     *
     * <p><b>금지할 코드를 그대로 적으면 안 된다.</b> 처음엔 나쁜 예에
     * {@code 주문 상태 PAID 확인 중입니다} 라고 쓰고 "이런 코드를 쓰지 말라"고 했는데,
     * <b>모델이 그 단어를 그대로 따라 썼다</b>(용어 누출 3건 전부 그 토큰이었다).
     * 금지어를 보여주는 것이 오히려 그 말을 떠올리게 한다. 그래서 <b>가려서</b> 쓴다.
     */
    private static final String BAD = """
            [나쁜 초안 — 이렇게 쓰지 마십시오]
              2026-08-30 결제 승인 완료 및 주문 상태(영문 코드) 확인 중입니다.
              에스크로 보류 자동 해제 예정일은 2026-09-06입니다.
            나쁜 이유: (1) 고객이 물어본 <금액이 왜 다른가>를 한 마디도 말하지 않았습니다.
              (2) 시스템 내부의 영문 대문자 코드를 우리말로 바꾸지 않고 그대로 썼습니다.
              (3) 에스크로 일정은 이 문의와 상관없는 정보입니다.
            """;

    /**
     * 이 건에 맞는 예시. <b>하나만 고른다</b> — 여러 개를 실으면
     * 모델이 상황에 안 맞는 쪽을 따라 쓴다(그게 바로 지금 고치려는 문제다).
     */
    public String forCase(FactPack facts) {
        String hint = facts.causeHint() == null ? "" : facts.causeHint();
        String chosen;
        if (hint.contains("INTERNAL_RECORD_LOST")) {
            chosen = NO_INTERNAL_RECORD;
        } else if (hint.contains("PG_FILE_DELAY") || hint.contains("NET_CANCEL_TIMING")) {
            chosen = FILE_DELAY;
        } else if (hint.contains("DECISIVE")) {
            chosen = DECISIVE;
        } else {
            // 원인이 없거나 확정되지 않은 것 — 가장 위험한 자리라 기본값으로 둔다.
            chosen = UNKNOWN_CAUSE;
        }
        return chosen + "\n" + BAD + """

                핵심: 사실을 나열하지 말고, <무엇이 문제이고 지금 어디까지 확인됐는지>를 쓰십시오.
                근거가 없는 것은 단정하지 마십시오.
                """;
    }
}
