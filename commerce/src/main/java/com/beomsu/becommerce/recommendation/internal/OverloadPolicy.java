package com.beomsu.becommerce.recommendation.internal;

/**
 * 모델 앞에서 <b>부하를 어떻게 다룰지</b> — E3의 독립변수.
 *
 * <p>셋의 차이는 "몇 개까지 받는가"가 아니라 <b>넘친 요청을 언제 포기하는가</b>다.
 */
public enum OverloadPolicy {

    /**
     * 아무도 거절하지 않는다. 모두 모델 앞에 줄을 선다.
     *
     * <p>모델은 살아 있는데 <b>API가 죽는다</b> — 요청 스레드가 줄에 갇히고, 대기 시간이 그대로
     * 응답 시간이 된다. E3의 가설이 이 정책을 가리킨다.
     */
    UNBOUNDED,

    /**
     * 줄의 길이에 상한을 둔다. 넘으면 <b>기다리지 않고 즉시</b> 포기한다.
     *
     * <p>포기가 빠르다는 것이 장점이고, 부하가 조금만 넘쳐도 <b>모두</b> 포기한다는 것이 단점이다 —
     * 상한 근처에서는 대기해도 됐을 요청까지 버린다.
     */
    BOUNDED,

    /**
     * 상한 대신 <b>대기 예상</b>을 본다. 예상이 예산을 넘으면 줄에 서지 않고 포기한다(Little의 법칙).
     *
     * <p>{@code BOUNDED}와 같은 "포기"지만 <b>판단 근거가 관측된 대기열</b>이라, 모델 용량이나
     * 예산이 바뀌어도 상한을 다시 고르지 않아도 된다. 대신 <b>모델 용량을 알아야</b> 한다.
     */
    ADMISSION
}
