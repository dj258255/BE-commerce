package com.beomsu.becommerce.ledger.internal;

/**
 * 원장 계정 유형(시스템 계정).
 *
 * <p>결제 한 건의 생애는 세 사건으로 원장에 남는다.
 * <pre>
 *   승인    (차) PG미수금        / (대) 매출
 *   취소    (차) 매출            / (대) PG미수금        ← 역분개
 *   입금    (차) 보통예금 + 수수료 / (대) PG미수금        ← 미수금 회수
 * </pre>
 *
 * <p>입금 분개가 있어야 <b>미수금 = 승인합 − 취소합 − 입금합</b>이 성립한다. 없으면 미수금이
 * 쌓이기만 해서 그 잔액이 실제 채권과 영원히 어긋난다.
 */
public enum AccountType {
    PG_RECEIVABLE,  // PG로부터 받을 돈(자산)
    SALES,          // 매출(수익)
    CASH,           // 보통예금(자산) — PG가 실제로 보내 준 돈
    PG_FEE          // 지급수수료+부가세(비용) — 우리가 부담해 미수금에서 차감되는 몫
}
