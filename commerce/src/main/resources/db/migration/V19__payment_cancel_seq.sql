-- 취소 순번(cancel_seq) 도입.
--
-- 문제: 취소를 "원결제 ID + 금액"으로 식별하고 있었다. 취소는 원결제당 여러 번 일어나므로 그 키로는
-- 식별이 안 된다. 20,000원 결제를 5,000원씩 두 번 부분취소하면 네 계층이 동시에 깨졌다.
--   ① PG 멱등키(paymentKey:금액)가 같아져 토스가 첫 취소 응답을 재생 → 2차 취소가 전송조차 안 됨
--   ② 취소 반영 가드가 상태 기반이라(PARTIAL_CANCELED는 취소 가능) 재진입이 안 막힘
--   ③ 원장 중복 판정이 paymentId만 봐서 2차 취소가 분개되지 않음
--   ④ 대사가 취소를 아예 구독하지 않아 취소된 건이 영구 불일치
--
-- 해결: 결제마다 지금까지 반영된 취소 건수를 들고, 다음 취소를 cancel_count + 1 로 식별한다.
-- 이 순번이 PG 멱등키·취소 반영 가드·원장 중복 판정의 공통 키가 된다.
--
-- 재시도 안전: 실패한 취소는 cancel_count를 올리지 않으므로 재시도가 같은 순번을 다시 계산하고,
-- 따라서 같은 PG 멱등키를 쓴다. 서로 다른 취소는 순번이 달라 키가 갈린다.
ALTER TABLE payments
    ADD COLUMN cancel_count INT NOT NULL DEFAULT 0;
