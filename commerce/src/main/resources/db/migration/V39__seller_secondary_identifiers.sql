-- 제재 스크리닝에 2차 식별자를 더한다.
--
-- 왜: 임계를 고르려고 이름 점수를 쟀더니 <같은 사람의 다른 로마자 표기>와 <아예 다른 사람>이
-- 둘 다 67점이었다. 그때는 "문자열 거리로는 못 가른다"고 적고 사람 검토로 보냈다.
--
-- 그런데 그 결론이 틀렸다. 실제 제재 스크리닝은 세 층으로 한다 —
--   1층 정확 일치(이름·별칭·생년월일·국적·문서번호)
--   2층 퍼지 매칭(편집거리·음역표·발음)
--   3층 맥락 판별(생년월일·국적·문서번호로 후보를 좁힌다)
-- 경보의 90% 이상이 오탐이라 3층이 실무의 핵심인데, 내가 만든 것은 2층까지였다.
-- 못 가른 이유는 거리 계산이 약해서가 아니라 <볼 것을 안 보고 있어서>다.
--
-- country_code 는 이미 있었는데 스크리닝이 안 쓰고 있었다. 생년월일만 새로 받는다.
-- 이건 범위 확장이 아니다 — 사업자등록에 대표자 생년월일이 들어 있고, 제재 대조를 하려면
-- 그게 있어야 한다. 없이 하면 흔한 이름이 전부 사람 검토로 넘어간다.
--
-- 실측(SecondaryIdentifierTest): 임계 80 기준 오판 이름만 2/4 → 식별자 포함 0/4.
--   같은 사람 다른 로마자   67점 → 82점
--   다른 사람 비슷한 이름   67점 → 12점
--   흔한 이름 남남        100점 → 45점

ALTER TABLE sellers
    ADD COLUMN representative_birth_date DATE NULL
        COMMENT '대표자 생년월일. 제재 명단 대조에서 동명이인을 가르는 데 쓴다. 모르면 NULL 이고, 그때는 이름 점수를 안 건드린다';
