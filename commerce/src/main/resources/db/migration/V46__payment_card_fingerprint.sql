-- 같은 카드를 결제 여러 건에 걸쳐 묶는 키를 결제에 붙인다.
--
-- 사후 탐지가 이력을 묶는 키로 쓰던 것은 payment_key 인데 그것은 결제마다 새로 발급된다.
-- 그래서 모델이 보는 창에 늘 이번 건 하나만 들어왔고, 같은 카드의 과거 결제를 보는 피처
-- (창 건수·금액 계단·과거 중앙값 대비 배수)가 사실상 죽어 있었다. 심사 화면의 "같은 카드의
-- 지난 심사"도 같은 이유로 늘 0 건이었다.
--
-- <b>카드 데이터를 저장하지 않는다.</b> 여기 들어가는 값은 PG 가 이미 마스킹해서 준 번호와
-- 발급사 코드를 SHA-256 으로 바꾼 것이고 원문은 어디에도 안 적는다. 되돌려도 마스킹된 값이다.
--
-- <b>이 키는 카드를 유일하게 가리키지 않는다.</b> 마스킹이 앞 여덟 자리와 뒤 몇 자리만 남기므로
-- 같은 발급사·같은 BIN 의 다른 카드가 같은 키를 받을 수 있다. 과하게 묶일 수는 있어도 갈라지지는
-- 않는다. 유일한 키가 필요하면 빌링키를 받아야 하고 그것은 자동결제 연동이 따로 필요하다.
--
-- 널을 허용한다. 카드 결제가 아니거나 PG 가 카드 정보를 안 주는 경로가 있고, 이미 쌓인 결제도
-- 채울 방법이 없다. 널이면 사후 탐지가 예전처럼 payment_key 로 떨어진다.
ALTER TABLE payments
    ADD COLUMN card_fingerprint varchar(64) NULL;

-- 카드 기준으로 과거 결제를 되읽는 조회에 쓴다.
CREATE INDEX idx_payments_card_fingerprint ON payments (card_fingerprint);

-- 심사가 같은 결제로 두 줄 생기던 것을 막는다.
--
-- 결제 완료 이벤트는 아웃박스라 at-least-once 다. card_transactions 는 V43 에서 order_no 에
-- 유니크를 걸어 이것을 막았는데 fraud_reviews 에는 안 걸려 있었다. 커밋은 됐는데 이벤트 완료
-- 표시가 실패하는 좁은 창에서 같은 결제가 두 줄이 되고, 그러면 "같은 카드의 지난 심사"가
-- 자기 자신을 과거 건으로 세게 된다. 카드 지문이 붙는 지금부터는 그 오염이 실제로 보인다.
ALTER TABLE fraud_reviews
    ADD CONSTRAINT uk_fraud_reviews_payment UNIQUE (payment_id);
