-- 고정(드롭)마다 고유한 판매 단위를 식별하는 세대 번호(R12, ADR-085 "다시 볼 조건" 수정).
--
-- 지금까지 LiveOrderGate의 Redis 선점 키는 broadcastId로만 범위를 잡았다 — 같은 방송에서
-- 상품을 다시 고정하면(완판된 상품을 다시 고정하거나 다른 상품으로 바꿔 고정) 이전 고정분의
-- 선점이 새 고정의 남은 수량에 그대로 섞여 들어가는 결함이 있었다.
--
-- generation은 pin()을 부를 때만(= 새 드롭을 걸 때만) 올라간다. changePrice()는 같은 드롭의
-- 연장이므로 generation을 올리지 않는다(올리면 가격만 바꿔도 선점 카운트가 리셋돼 한도보다
-- 더 팔릴 수 있다) — seq와 다른 축이다. 기존 행은 0으로 채운다(지금까지 각 방송은 고정을
-- 한 번만 했으므로 0이 맞다 — 이미 고정 중인 행도 지금 선점 중인 주문이 없으므로 안전하다).
alter table live_pins
    add column generation bigint not null default 0;
