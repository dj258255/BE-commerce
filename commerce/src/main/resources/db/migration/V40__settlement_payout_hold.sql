-- 정산에 <지급 보류>를 더한다.
--
-- 왜: 제재 스크리닝에 걸린 판매자의 정산은 <집계는 하되 돈은 안 나가야> 한다.
-- 집계까지 건너뛰면 나중에 심사가 풀렸을 때 그 날짜 매출이 영영 안 잡힌다 —
-- 이 집계 키는 이미 한 번 조용히 틀려 지급이 통째로 빠졌던 자리다(V-정산 기준일 수정).
-- 그래서 정산은 만들고 상태로 표시한다.
--
-- status 는 VARCHAR 라 값 추가에 제약 변경이 필요 없다. PAYOUT_HELD 가 늘어난다.
ALTER TABLE settlements
    ADD COLUMN payout_hold_reason VARCHAR(200) NULL
        COMMENT '지급을 막은 이유. 화면에 그대로 나가므로 사람이 읽을 말이다. 안 막았으면 NULL';
