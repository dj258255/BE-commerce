-- 정산 항목에 마지막 반영 취소 순번을 둔다.
--
-- 취소 후 잔액을 절대값으로 세팅하는 것은 <중복 배달>에는 멱등이지만 <순서 역전>에는 안전하지 않다.
-- 1차 취소 후 잔액 7,000, 2차 후 4,000인데 2차가 먼저 소비되면 늦게 온 1차가 4,000을 7,000으로
-- 되돌린다. 순번을 함께 보면 오래된 취소를 무시할 수 있다.
--
-- 기존 행은 -1 로 채운다. 아직 취소를 반영한 적이 없다는 뜻이고, 순번 0인 첫 취소도 통과한다.
ALTER TABLE settlement_items
    ADD COLUMN last_cancel_seq INT NOT NULL DEFAULT -1;
