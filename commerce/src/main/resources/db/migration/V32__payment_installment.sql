-- 할부 개월을 결제에 남긴다.
--
-- 왜 저장하나: 할부는 우리 정산 금액을 바꾸지 않는다. 고객이 12개월로 나눠 내도 카드사가
-- 가맹점에는 일시에 전액을 지급하고, 분납은 카드사와 고객 사이의 일이다. 그래서 대사·정산은
-- 이 값을 보지 않는다. 그럼에도 남기는 이유는 둘이다.
--   1) 운영자가 대사 화면에서 건을 판단할 때 필요하다
--   2) 이상거래 판정이 이 값을 본다 — 한도 안에서 결제 금액을 키우는 가장 쉬운 수단이 할부라,
--      "고액 + 장기 할부"는 도난 카드에서 흔한 모양이다
--
-- 0 = 일시불. 기존 행은 전부 일시불로 채운다(할부를 받기 전에 만들어진 건들이다).
ALTER TABLE payments
    ADD COLUMN installment_months INT NOT NULL DEFAULT 0 AFTER method;
