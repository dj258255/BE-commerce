package com.beomsu.becommerce.seller.screening;

/**
 * 기계 판정. <b>확정은 사람이 한다</b>는 이 프로젝트의 순서가 여기서도 같다.
 *
 * <p>세 갈래인 이유: 통과와 차단만 두면 <b>애매한 것을 어느 한쪽으로 밀어야 한다.</b>
 * 밀어서 통과시키면 제재 대상에게 돈이 가고, 밀어서 차단하면 멀쩡한 판매자가 묶인다.
 * 애매한 것은 애매하다고 두고 사람에게 넘긴다.
 */
public enum ScreeningVerdict {
    /** 임계 아래. 명단에 없는 것으로 본다. */
    CLEAR,
    /** 잠재 일치. <b>지급을 막고 사람이 본다.</b> 오탐률의 분모가 여기서 나온다. */
    POTENTIAL,
    /** 정규화 후 완전 일치. 그래도 자동 차단은 안 하고 사람이 확인한다. */
    CONFIRMED
}
